import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { getCurrentUserId } from "@/lib/auth";
import { isFounderUser } from "@/lib/cron";
import { RESEARCH_REPORT_SELECT, parseTopic, titleFromTopic, toResearchReportView } from "@/lib/research/report";

export const dynamic = "force-dynamic";

export async function GET(request: Request) {
  const userId = await getCurrentUserId(request);
  if (!userId) return NextResponse.json({ error: "unauthorized" }, { status: 401 });

  const rows = await prisma.researchReport.findMany({
    where: { userId },
    orderBy: { createdAt: "desc" },
    select: RESEARCH_REPORT_SELECT,
    take: 200,
  });
  return NextResponse.json({ reports: rows.map(toResearchReportView) });
}

export async function POST(request: Request) {
  const userId = await getCurrentUserId(request);
  if (!userId) return NextResponse.json({ error: "unauthorized" }, { status: 401 });
  // Reports are generated by Claude Code on Eddie's Mac with full permissions,
  // so only the founder may queue a topic (the worker also only claims theirs).
  if (!(await isFounderUser(userId))) {
    return NextResponse.json({ error: "Research reports aren't enabled for this account." }, { status: 403 });
  }

  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: "invalid JSON" }, { status: 400 });
  }
  const parsed = parseTopic(body);
  if ("error" in parsed) return NextResponse.json({ error: parsed.error }, { status: 400 });

  const row = await prisma.researchReport.create({
    data: { userId, topic: parsed.topic, title: titleFromTopic(parsed.topic), status: "queued" },
    select: RESEARCH_REPORT_SELECT,
  });
  return NextResponse.json({ report: toResearchReportView(row) });
}
